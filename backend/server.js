require('dotenv').config();
const express=require('express');const mongoose=require('mongoose');const cors=require('cors');
const app=express();
app.use(cors({origin:process.env.CLIENT_URL?process.env.CLIENT_URL.split(','):true}));
app.use(express.json());
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'SmartSpend AI API'}));
app.use('/api/auth',require('./routes/auth'));
app.use('/api/transactions',require('./routes/transactions'));
app.use('/api/budgets',require('./routes/budgets'));
const PORT=process.env.PORT||5000;
mongoose.connect(process.env.MONGO_URI).then(()=>{console.log('MongoDB connected');app.listen(PORT,()=>console.log(`SmartSpend API running on ${PORT}`));}).catch(err=>{console.error('MongoDB connection failed:',err.message);process.exit(1);});
